import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const directory = new URL('../supabase/migrations/', import.meta.url);
const names = (await readdir(directory)).filter(name => name.endsWith('.sql')).sort();
if (!names.length) throw new Error('No Supabase migrations found.');

const sections = [];
for (const name of names) {
  const source = await readFile(new URL(name, directory), 'utf8');
  if (!/^begin;\r?$/m.test(source) || !/^commit;\r?$/m.test(source)) {
    throw new Error(`${name} must have explicit transaction wrappers.`);
  }
  sections.push(`-- Source: migrations/${name}\n${source.replace(/^begin;\r?\n|^commit;\r?\n?/gm, '').trim()}`);
}

const target = new URL('../supabase/setup.sql', import.meta.url);
const header = '-- Generated by npm run db:bundle. Do not edit this file directly.\n' +
  '-- Initial setup for a project where TrueDeal tables do not exist yet.\n' +
  '-- Run the entire file in Supabase SQL Editor. All changes are atomic.\n' +
  '-- No demo users, operator grants, paid orders or payment activation are seeded.\n';
await writeFile(target, `${header}\nbegin;\n\n${sections.join('\n\n')}\n\ncommit;\n`);
console.log(`Prepared ${fileURLToPath(target)} from ${names.length} migrations.`);
